#!/usr/bin/env python3
"""Regenerate app/lib/radioTracks.ts from the Tru Collective app catalog.

Run after the catalog changes (new songs, hold-list edits):
    python3 scripts/generate-radio-tracks.py [path-to-tru-collective-app-repo] [--exclude-held]

Eligibility:
  - held songs (src/data/hold.json)          -> INCLUDED by default (Kevin's call,
    2026-10-09: the radio plays held songs too). Pass --exclude-held to follow
    the app's hold list instead.
  - songs still in the Fresh Produce window  -> excluded (app-first drops)
  - `protected: true` songs                  -> excluded. In the app these only
    play when a listener's mood/intention matches (guardrailAllows in
    recommend.ts). A radio has no mood-matching, so they'd surface at random.

Per-artist keep-lists (ARTIST_KEEP below): for a listed artist, ONLY the named
songs are eligible. Mercy Hearts is trimmed to 7 songs at Kevin's direction
(2026-10-09).

Durations are measured with ffprobe against the public audio files (not trusted
from catalog.json) because the radio schedule is computed from them — a few
seconds of error per song would put listeners out of sync with the audio.
"""
import json, subprocess, sys, os, datetime
from concurrent.futures import ThreadPoolExecutor

ARGS = [a for a in sys.argv[1:] if not a.startswith("--")]
EXCLUDE_HELD = "--exclude-held" in sys.argv
APP = os.path.expanduser(ARGS[0] if ARGS else "~/tru-collective")
SUPA = "https://wwdjwzdlkyijvtaqlmqz.supabase.co"
FRESH_WINDOW_DAYS = 11

catalog = json.load(open(f"{APP}/src/data/catalog.json"))
held = {h["id"] for h in json.load(open(f"{APP}/src/data/hold.json"))}
fresh_entries = json.load(open(f"{APP}/src/data/fresh.json"))
now = datetime.datetime.now(datetime.timezone.utc)
fresh = set()
for f in fresh_entries:
    added = datetime.datetime.fromisoformat(f["dateAdded"]).replace(tzinfo=datetime.timezone.utc)
    if (now - added).days <= FRESH_WINDOW_DAYS:
        fresh.add(f["id"])

# For these artists only the listed song IDs are eligible; everything else by them is out.
ARTIST_KEEP = {
    "Mercy Hearts": {
        "MERCY-045",  # Pocket full of stars
        "MERCY-055",  # Entangled
        "MERCY-049",  # Growing up is Hard
        "MERCY-015",  # Drove Away
        "MERCY-033",  # Slow Burn
        "MERCY-042",  # Open Road Faith
        "MERCY-024",  # No Loose Ends
    },
}

# Songs pulled from the radio by request, whatever else is true of them.
NEVER_PLAY = {
    "KAI-047",  # Feared By Weak men
}

eligible = [
    t for t in catalog
    if t["id"] not in NEVER_PLAY
    and (not EXCLUDE_HELD or t["id"] not in held)
    and t["id"] not in fresh
    and not t.get("protected")
    and (t["artist"] not in ARTIST_KEEP or t["id"] in ARTIST_KEEP[t["artist"]])
]
print(f"catalog {len(catalog)} | held {len(held)} | fresh {len(fresh)} | "
      f"protected {sum(1 for t in catalog if t.get('protected'))} | eligible {len(eligible)}")


def probe(t):
    url = f"{SUPA}/storage/v1/object/public/audio/{t['audioFile']}"
    out = subprocess.run(
        ["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "json", url],
        capture_output=True, text=True, timeout=120,
    )
    return t["id"], float(json.loads(out.stdout)["format"]["duration"])


with ThreadPoolExecutor(8) as ex:
    real = dict(ex.map(probe, eligible))

drift = [(t["id"], t["duration"], real[t["id"]]) for t in eligible if abs(t["duration"] - real[t["id"]]) > 1.0]
print(f"{len(drift)} tracks where catalog.json duration is off by >1s (using measured values):")
for i, c, r in drift[:10]:
    print(f"  {i}: catalog {c:.1f}s vs measured {r:.1f}s")

# Stable order (by id) so the generated file diffs cleanly; the radio shuffles at runtime.
eligible.sort(key=lambda t: t["id"])
lines = [
    "// GENERATED by scripts/generate-radio-tracks.py — do not edit by hand.",
    "// Re-run that script after the app catalog or hold list changes.",
    f"// Generated {now.strftime('%Y-%m-%d')} · {len(eligible)} songs · "
    f"{sum(real[t['id']] for t in eligible) / 3600:.2f} h per cycle.",
    "export type RadioTrack = {",
    "  id: string; title: string; artist: string; genre: string;",
    "  audioFile: string; artFile: string; duration: number;",
    "};",
    "",
    "export const RADIO_TRACKS: RadioTrack[] = [",
]
for t in eligible:
    lines.append(
        "  { id: %s, title: %s, artist: %s, genre: %s, audioFile: %s, artFile: %s, duration: %.3f },"
        % (json.dumps(t["id"]), json.dumps(t["title"], ensure_ascii=False), json.dumps(t["artist"]),
           json.dumps((t.get("genre") or [""])[0]), json.dumps(t["audioFile"]), json.dumps(t["artFile"]),
           real[t["id"]])
    )
lines.append("];")
lines.append("")
dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app", "lib", "radioTracks.ts")
open(dest, "w").write("\n".join(lines))
print("wrote", os.path.normpath(dest))
